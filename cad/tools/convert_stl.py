#!/usr/bin/env python3
"""
cad/tools/convert_stl.py

Utility to convert ASCII STL files to compact Binary STL files,
and validate triangle counts and byte integrity.
"""

import sys
import os
import struct

def is_ascii_stl(filepath):
    """Check if STL is in ASCII format."""
    with open(filepath, 'rb') as f:
        head = f.read(200)
    return head.startswith(b'solid') and b'facet' in head

def ascii_to_binary_stl(ascii_path, bin_path, header_comment="Generated by load_cell_joystick tool"):
    """Stream-convert ASCII STL to compact Binary STL."""
    temp_path = bin_path + ".tmp"
    header = header_comment.encode('ascii', errors='ignore').ljust(80, b' ')[:80]
    num_facets = 0

    with open(ascii_path, 'r', encoding='utf-8', errors='ignore') as fin, open(temp_path, 'wb') as fout:
        fout.write(header)
        fout.write(struct.pack('<I', 0))  # Placeholder for triangle count
        floats = []
        for line in fin:
            parts = line.strip().split()
            if not parts:
                continue
            if parts[0] == 'facet' and len(parts) >= 5 and parts[1] == 'normal':
                floats.extend([float(parts[2]), float(parts[3]), float(parts[4])])
            elif parts[0] == 'vertex' and len(parts) >= 4:
                floats.extend([float(parts[1]), float(parts[2]), float(parts[3])])
            elif parts[0] == 'endfacet':
                if len(floats) == 12:
                    fout.write(struct.pack('<12fH', *floats, 0))
                    num_facets += 1
                floats = []
        fout.seek(80)
        fout.write(struct.pack('<I', num_facets))

    os.replace(temp_path, bin_path)
    orig_sz = os.path.getsize(ascii_path) / 1024 / 1024
    bin_sz = os.path.getsize(bin_path) / 1024 / 1024
    print(f"Converted '{ascii_path}' -> '{bin_path}': {num_facets:,} triangles ({orig_sz:.2f} MB -> {bin_sz:.2f} MB)")
    return num_facets

def verify_binary_stl(filepath):
    """Verify binary STL structure and triangle count."""
    size = os.path.getsize(filepath)
    if size < 84:
        raise ValueError(f"File {filepath} is too small to be a binary STL ({size} bytes)")
    with open(filepath, 'rb') as f:
        header = f.read(80)
        num_triangles = struct.unpack('<I', f.read(4))[0]
    expected_size = 84 + num_triangles * 50
    if size != expected_size:
        raise ValueError(f"File {filepath} corrupted: expected {expected_size} bytes for {num_triangles} triangles, got {size} bytes")
    print(f"Verified Binary STL '{filepath}': {num_triangles:,} triangles ({size/1024/1024:.2f} MB)")
    return num_triangles

if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Usage: convert_stl.py <input.stl> <output.stl> [verify]")
        sys.exit(1)
    in_f = sys.argv[1]
    out_f = sys.argv[2]
    if len(sys.argv) > 3 and sys.argv[3] == "verify":
        verify_binary_stl(in_f)
    else:
        ascii_to_binary_stl(in_f, out_f)
